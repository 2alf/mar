import os as _os
def _find_root():
    d = _os.path.dirname(_os.path.abspath(__file__))
    while not _os.path.exists(_os.path.join(d, 'lakefile.toml')):
        nd = _os.path.dirname(d)
        if nd == d:
            raise RuntimeError('repository root (lakefile.toml) not found')
        d = nd
    return d
ROOT = _find_root()
import json, sys
sys.path.insert(0,(ROOT + '/data'))
from ctparse import load
W=json.load(open('baby_witness.json'))
T=load('2.B',(ROOT + '/data/ctomonst.tbl')); TB=load('B',(ROOT + '/data/ctomonst.tbl'))
L=lambda xs:'['+', '.join(str(x) for x in xs)+']'
S=lambda xs:'['+', '.join('"%s"'%x for x in xs)+']'
out=['''/-
# Data for the double cover `2.B` of the Baby Monster (AUTO-GENERATED by `data/gen_baby_lean.py`)

Source: GAP Character Table Library 1.3.11, `data/ctomonst.tbl`, tables `"2.B"` and `"B"`
(ATLAS). Classes are 0-based in ctbllib order. `bbFus` is the class fusion `2.B → B`
(`ALF("2.B","B",…)`); `bChi2` is the character of `B` of degree 4371.
Witness permutations were found by a maintained-arc-consistency search (`data/baby_labels.py`)
and are re-checked by the kernel in `MonsterCN.BabyMonster`.
-/
namespace MonsterCN.Baby
''']
out.append('def bbPrimes : List Nat := '+L(T['primes']))
out.append('def bbNames : List String := '+S(T['names']))
out.append('def bbOrd : List Nat := '+L(T['orders']))
out.append('def bbCent : List Nat := '+L(T['cent']))
out.append('def bbPmap : Nat → List Nat')
for p in T['primes']: out.append('  | %d => %s'%(p,L(T['pmaps'][p])))
out.append('  | _ => []')
out.append('def bbFus : List Nat := '+L(W['fus']))
out.append('def bNames : List String := '+S(TB['names']))
out.append('def bChi2 : List Int := '+L(W['chi2B']))
ws=[w for w in W['witnesses'] if w['h1'][0]!=w['h1'][1]]
out.append('/-- Witness permutations `(c, d, π)` with `π c = d`. -/')
out.append('def witnesses : List (Nat × Nat × List Nat) := [\n'+',\n'.join('  (%d, %d, %s)'%(w['c'],w['d'],L(w['perm'])) for w in ws)+']')
out.append('end MonsterCN.Baby\n')
open('../MonsterCN/Data/Baby.lean','w',encoding='utf8').write('\n'.join(out))
print(len(ws),'witnesses written;', [(T['names'][w['c']],T['names'][w['d']]) for w in ws])
