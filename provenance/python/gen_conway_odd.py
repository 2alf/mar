"""Generate MonsterCN/Data/ConwayOdd.lean: odd-order classes of Co0, their frame shapes, DMC labels
(parsed to CNLabel), and the alternative labelling used for MAR-15."""
import os as _os
def _find_root():
    d = _os.path.dirname(_os.path.abspath(__file__))
    while not _os.path.exists(_os.path.join(d, 'lakefile.toml')):
        nd = _os.path.dirname(d)
        if nd == d:
            raise RuntimeError('repository root (lakefile.toml) not found')
        d = nd
    return d
ROOT = _find_root()
import json, re, sys
sys.path.insert(0, (ROOT + '/ogg'))
from common import exact_divisors

D = json.load(open('co0_data.json'))
L = json.load(open('co0_labels.json'))
F = json.load(open('co0_frames.json'))
names = D['names']; orders = D['orders']
lab = list(L['lab'])
plain = re.compile(r'^(\d+)(?:\|(\d+))?([-+](?:\d+(?:,\d+)*)?)?$')

def parse(s):
    m = plain.match(s)
    n = int(m.group(1)); h = int(m.group(2) or 1); r = m.group(3) or '-'; q = n // h
    W = {1} if r == '-' else set(exact_divisors(q)) if r == '+' else {1} | {int(x) for x in r[1:].split(',')}
    return n, h, sorted(W)

O = [c for c in range(len(names)) if orders[c] % 2 == 1]
lbl = lambda t: '⟨%d, %d, [%s]⟩' % (t[0], t[1], ', '.join(map(str, t[2])))
out = ['''/-
# Odd-order classes of Co0 (AUTO-GENERATED by `data/gen_conway_odd.py`)

`oddClasses`: indices (into `MonsterCN.Conway.coNames`) of the 29 classes of odd order.
`frameShape c`: the frame shape `∏ m^{a_m}` of class `c` on the 24-dimensional Leech representation,
as a list of `(m, a_m)`. It was computed from `χ₂₄` on powers in `data/co0_frames.py`, and
`MonsterCN.ConwayOdd.frame_matches_chi24` re-checks it in the kernel.
`dmcOdd c`: the Duncan–Mack-Crane label of `c`, parsed into `CNLabel` form.
-/
import MonsterCN.Data.CNTable

namespace MonsterCN.ConwayOdd

open MonsterCN
''']
out.append('def oddClasses : List Nat := [' + ', '.join(map(str, O)) + ']')
out.append('def frameShape : Nat → List (Nat × Int)')
for c in O:
    fr = sorted((int(m), k) for m, k in F['frames'][c].items())
    out.append('  | %d => [%s]' % (c, ', '.join('(%d, %d)' % x for x in fr)))
out.append('  | _ => []')
out.append('def dmcOdd : Nat → CNLabel')
for c in O:
    out.append('  | %d => %s  -- %s: %s' % (c, lbl(parse(lab[c])), names[c], lab[c]))
out.append('  | _ => ⟨0, 0, []⟩')
out.append('end MonsterCN.ConwayOdd\n')
open('../MonsterCN/Data/ConwayOdd.lean', 'w', encoding='utf8').write('\n'.join(out))
print('odd classes:', [names[c] for c in O])
print('9A,9B,9C indices:', [O[k] for k in range(len(O)) if names[O[k]] in ('9A', '9B', '9C')])
