"""Generate Lean data files from ctbllib's ctomonst.tbl (table "M") and the
Conway-Norton label table (monster_cn_labels.tsv, transcribed from
Duncan-Griffin-Ono arXiv:1411.6571 App. A, cross-checked against Conway-Norton 1979 Table 2)."""
import re, json, sys
txt=open('ctomonst.tbl').read()
s=txt[txt.index('MOT("M",')+len('MOT('):]
toks=re.findall(r'"[^"]*"|-?[0-9]+|[][(),]|[A-Za-z_]+|[^\s]',s)
pos=0
def parse():
    global pos
    t=toks[pos]
    if t=='[':
        pos+=1; lst=[]; cur=None; have=False
        while True:
            t=toks[pos]
            if t==']':
                pos+=1
                if have: lst.append(cur)
                return lst
            if t==',':
                pos+=1; lst.append(cur if have else None); cur=None; have=False; continue
            cur=parse(); have=True
    pos+=1
    if t.startswith('"'): return t
    if re.match(r'-?\d+$',t): return int(t)
    return t
ident=parse(); pos+=1; text=parse(); pos+=1; cent=parse(); pos+=1; pm=parse(); pos+=1
# irreducibles: parse only first 4 rows robustly
assert toks[pos]=='['; pos+=1
irr=[]
for k in range(4):
    r=parse(); irr.append(r); assert toks[pos]==','; pos+=1
N=len(cent); assert N==194
for r in irr: assert len(r)==N and all(isinstance(x,int) for x in r), r[:5]
primes=[p+1 for p,m in enumerate(pm) if m is not None]
A=[l.split('\t') for l in open('atlas_names.tsv').read().split('\n') if l]
names=[a[0] for a in A]; order=[int(a[1]) for a in A]
assert [int(a[2]) for a in A]==cent
lab={}
for l in open('monster_cn_labels.tsv').read().split('\n')[1:]:
    if l: a,b=l.split('\t'); lab[a]=b
from math import gcd
def hall(q): return [e for e in range(1,q+1) if q%e==0 and gcd(e,q//e)==1]
def parselab(s):
    m=re.match(r'(\d+)(?:\|(\d+))?(.*)$',s); n=int(m.group(1)); h=int(m.group(2) or 1); r=m.group(3); q=n//h
    W=[1] if r in('','-') else hall(q) if r=='+' else sorted({1}|{int(x) for x in r[1:].split(',')})
    return n,h,W
def L(xs): return '[' + ', '.join(str(x) for x in xs) + ']'
out=[]
out.append('''/-
# ATLAS data for the Monster group `M` (AUTO-GENERATED by `data/gen_lean.py`)

Source: GAP Character Table Library (ctbllib 1.3.11, T. Breuer), file `data/ctomonst.tbl`,
table `"M"` (origin: ATLAS of Finite Groups). Classes are indexed `0 … 193` in ATLAS order.
* `className`, `ord` : ATLAS class names and element orders. ctbllib does not store these; GAP
  derives them from the power maps. `ord` is re-derived from the power maps and checked in
  `MonsterCN.Checks`.
* `cent` : centralizer orders `|C_M(g)|`.
* `pmap p` : the `p`-th power map, for the 15 primes `p` dividing `|M|`.
* `chi2 chi3 chi4` : the irreducible characters of degrees 196883, 21296876, 842609326.

**External assumption (documented, not an axiom):** these lists are the ATLAS data of the Monster.
Lean does not (and currently cannot) check them against a Lean model of the Monster.
-/
namespace MonsterCN

/-- Number of conjugacy classes of the Monster. -/
def numClasses : Nat := 194

/-- The 15 primes dividing `|M|`. -/
def monsterPrimes : List Nat := ''' + L(primes) + '''

/-- `|M|`. -/
def monsterOrder : Nat := ''' + str(cent[0]) + '''
''')
out.append('def className : List String := [' + ', '.join('"%s"'%n for n in names) + ']\n')
out.append('def ord : List Nat := ' + L(order) + '\n')
out.append('def cent : List Nat := ' + L(cent) + '\n')
out.append('/-- `pmap p` is the `p`-th power map (0-based class indices); `[]` for other `p`. -/')
out.append('def pmap : Nat → List Nat')
for p in primes:
    out.append('  | %d => %s' % (p, L([x-1 for x in pm[p-1]])))
out.append('  | _ => []\n')
for k,nm in [(1,'chi2'),(2,'chi3'),(3,'chi4')]:
    out.append('def %s : List Int := %s\n' % (nm, '[' + ', '.join(str(x) for x in irr[k]) + ']'))
out.append('end MonsterCN\n')
open('../MonsterCN/Data/Atlas.lean','w',encoding='utf8').write('\n'.join(out))
o=['''/-
# The Conway–Norton table (AUTO-GENERATED by `data/gen_lean.py`)

For each Monster class (ATLAS order, as in `MonsterCN.Data.Atlas`), the moonshine group
`Γ_g = n|h + e, f, …` of its McKay–Thompson series, encoded as `⟨n, h, W⟩` where `W` is the full
(sorted) set of Atkin–Lehner indices `e` (exact divisors of `n/h`), including `1`.
`n|h+` means all exact divisors; `n|h-` / `n|h` means `W = {1}`.

Source: Duncan–Griffin–Ono, *Moonshine*, Res. Math. Sci. 2 (2015), arXiv:1411.6571, Appendix A;
cross-checked against Conway–Norton, *Monstrous Moonshine*, Bull. LMS 11 (1979), Table 2.
-/
namespace MonsterCN

/-- A Conway–Norton label `n|h + W`. -/
structure CNLabel where
  n : Nat
  h : Nat
  W : List Nat
  deriving DecidableEq, Repr
''']
o.append('def cnTable : List CNLabel := [')
rows=[]
for nm in names:
    n,h,W=parselab(lab[nm]); rows.append('  ⟨%d, %d, %s⟩ /- %s : %s -/' % (n,h,L(W),nm,lab[nm]))
o.append(',\n'.join(rows)); o.append(']\n')
o.append('end MonsterCN\n')
open('../MonsterCN/Data/CNTable.lean','w',encoding='utf8').write('\n'.join(o))
print('ok', primes)
