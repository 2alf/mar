"""Regenerate MonsterCN/Data/Parents.lean from pmaps.json (pairs (d,p) with d^p = c, d != c)."""
import json
pm={int(k):v for k,v in json.load(open('pmaps.json')).items()}
par=[[] for _ in range(194)]
for d in range(194):
    for p in sorted(pm):
        c=pm[p][d]-1
        if c!=d: par[c].append((d,p))
s='/-! AUTO-GENERATED by data/gen_parents.py: for each class `c`, pairs `(d, p)` with `d^p = c`, `d ≠ c`.\nCorrectness is not assumed: every use re-checks `pw p d = c`. -/\nnamespace MonsterCN\n\ndef parentsTbl : List (List (Nat × Nat)) := [\n'
s+=',\n'.join('  ['+', '.join('(%d, %d)'%x for x in l)+']' for l in par)+'\n]\n\nend MonsterCN\n'
open('../MonsterCN/Data/Parents.lean','w',encoding='utf8').write(s)
